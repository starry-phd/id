/** AI-1 Round4: Starry ID server-controlled Session persistence. DRAFT D1 port.
 * Enforce existing active user + immutable Apple/Google subject using ONE INSERT
 * SELECT statement. Fixed prepared SQL only; never trust client JSON.
 * Production still requires AI-0 migration Gate, real D1 concurrency tests.
 */
import type {D1Database} from './d1-ports.ts';
import type {TrustedScope,Provider} from './index.ts';
const id=(s:unknown):s is string=>typeof s==='string'&&/^[A-Za-z0-9._:-]{1,180}$/.test(s);
const hash=(s:unknown):s is string=>typeof s==='string'&&/^[a-f0-9]{64}$/.test(s);
const time=(v:unknown):v is number=>typeof v==='number'&&Number.isSafeInteger(v)&&v>=0;
type SessionWrite=Readonly<{
  s_user_id:string;provider:Provider;provider_subject:string;
  session_id:string;refresh_hash:string;auth_version:number;
  expires_at:number;now:number;
}>;
type RotateWrite=Readonly<{
  s_user_id:string;session_id:string;auth_version:number;
  previous_hash:string;next_hash:string;expires_at:number;now:number;
}>;
export function createStarrySessionPersistence(db:D1Database,trustedScope:TrustedScope){
 const scope=Object.freeze({...trustedScope});
 if(scope.brand_id!=='starry'||!id(scope.app_id)||
     !['development','staging','production'].includes(scope.environment))
   throw Error('SESSION_DB_SCOPE_DENIED');
 return Object.freeze({
  async createForExistingMember(data:SessionWrite):Promise<boolean>{
   if(!id(data.s_user_id)||!id(data.session_id)||!id(data.provider_subject)||
     !['apple','google'].includes(data.provider)||!hash(data.refresh_hash)||
     !time(data.now)||!time(data.expires_at)||data.expires_at<=data.now||
     data.expires_at-data.now>30*86400||
     !Number.isSafeInteger(data.auth_version)||data.auth_version<1)return false;
   // No account autocreation or implicit email association.
   const r=await db.prepare(
     "INSERT INTO starry_sessions(session_id,s_user_id,app_id,environment,auth_version,refresh_hash,expires_at) "+
     "SELECT ?,m.s_user_id,?,?,m.auth_version,?,? FROM starry_members m "+
     "JOIN starry_identities i ON i.s_user_id=m.s_user_id "+
     "WHERE m.s_user_id=? AND m.status='active' AND m.auth_version=? AND i.provider=? AND i.subject=?"
   ).bind(data.session_id,scope.app_id,scope.environment,data.refresh_hash,data.expires_at,
      data.s_user_id,data.auth_version,data.provider,data.provider_subject).run();
   return r.success!==false&&r.meta?.changes===1;
  },
  /** Refresh is a single D1 CAS. Never issue next bearer if not 1 changed row. */
  async rotateRefreshCAS(data:RotateWrite):Promise<boolean>{
   if(!id(data.s_user_id)||!id(data.session_id)||!hash(data.previous_hash)||
      !hash(data.next_hash)||data.previous_hash===data.next_hash||
      !time(data.now)||!time(data.expires_at)||data.expires_at<=data.now||
      data.expires_at-data.now>30*86400||
      !Number.isSafeInteger(data.auth_version)||data.auth_version<1)return false;
   const r=await db.prepare(
     "UPDATE starry_sessions SET refresh_hash=?,expires_at=? "+
     "WHERE session_id=? AND s_user_id=? AND app_id=? AND environment=? "+
     "AND auth_version=? AND refresh_hash=? AND revoked_at IS NULL AND expires_at>? "+
     "AND EXISTS(SELECT 1 FROM starry_members m WHERE m.s_user_id=starry_sessions.s_user_id "+
     "AND m.status='active' AND m.auth_version=starry_sessions.auth_version)"
   ).bind(data.next_hash,data.expires_at,data.session_id,data.s_user_id,scope.app_id,
      scope.environment,data.auth_version,data.previous_hash,data.now).run();
   return r.success!==false&&r.meta?.changes===1;
  },
  /** Auth version bump revokes all sessions in same DB transaction? Not here.
   * With per-statement D1 it must be AI-0-approved batch/transaction adapter.
   * A member auth_version bump alone invalidates old JWT via current resolver. */
  async bumpMemberVersionCAS(sUserId:string,expectedVersion:number,now:number):Promise<boolean>{
   if(!id(sUserId)||!Number.isSafeInteger(expectedVersion)||expectedVersion<1||
     expectedVersion===Number.MAX_SAFE_INTEGER||!time(now))return false;
   const r=await db.prepare(
     "UPDATE starry_members SET auth_version=auth_version+1,updated_at=? "+
     "WHERE s_user_id=? AND status='active' AND auth_version=?"
   ).bind(now,sUserId,expectedVersion).run();
   return r.success!==false&&r.meta?.changes===1;
  },
 });
}
/** Raw refresh secrets are generated by secure server entropy, never DB/client flags. */
export async function hashServerRefreshSecret(raw:Uint8Array):Promise<string>{
 if(!(raw instanceof Uint8Array)||raw.byteLength<32||raw.byteLength>256)
   throw Error('REFRESH_SECRET_DENIED');
 const bytes=new Uint8Array(raw.byteLength);bytes.set(raw);
 const digest=await crypto.subtle.digest('SHA-256',bytes);
 return Array.from(new Uint8Array(digest),b=>b.toString(16).padStart(2,'0')).join('');
}
